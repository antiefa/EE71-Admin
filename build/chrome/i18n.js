  function resolveLocale(preferred) {
    if (preferred === "ru" || preferred === "en") {
      return preferred;
    }
    const language = (global.navigator && global.navigator.language) || "en";
    return String(language).toLowerCase().startsWith("ru") ? "ru" : "en";
  }

  function translate(locale, key, params) {
    const table = MESSAGES[locale] || MESSAGES.en;
    const template = table[key] || MESSAGES.en[key] || key;
    if (!params) {
      return template;
    }
    return Object.entries(params).reduce(
      (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
      template
    );
  }

  global.EE71_I18N = Object.freeze({ MESSAGES, resolveLocale, translate });
